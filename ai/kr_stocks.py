def is_bare_code(tk):
    """접미사 없는 한국 6자리 종목코드인가."""
    return bool(re.fullmatch(r"\d{6}", tk or ""))


def name_to_ticker(query):
    """문장/티커에서 한국 종목을 뽑는다.
       이름이 잡히면 .KS/.KQ 붙은 티커, 6자리 코드면 그대로(bare), 없으면 None."""
    ql = (query or "").lower()
    for name, tk in NAME2TICKER_KR.items():
        if name in ql:
            return tk
    m = re.search(r"\b(\d{6})\b", query or "")
    if m:
        return m.group(1)
    return None
